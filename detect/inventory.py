"""Turn scan findings plus owner-declared service manifests into a migration inventory.

A service directory is any directory holding `atlas-service.json` (id, name, kind, data_class,
depends_on: ownership facts the scanner cannot infer). The crypto facts (algorithm, evidence)
come only from the scan. Services with no quantum-vulnerable finding are listed separately and
left out of the migration inventory. Output matches schedule/data/*_assets.json.
"""

import json
from pathlib import Path

VULNERABLE = ("RSA", "ECC", "DH", "DSA")
MANIFEST = "atlas-service.json"


def service_dirs(root: Path) -> dict[str, Path]:
    out = {}
    for m in sorted(root.rglob(MANIFEST)):
        out[m.parent.relative_to(root).as_posix()] = m.parent
    return out


def owner(findings_file: str, dirs: dict[str, Path]) -> str | None:
    best = None
    for prefix in dirs:
        if findings_file.startswith(prefix + "/") and (best is None or len(prefix) > len(best)):
            best = prefix
    return best


def algorithm_summary(findings: list[dict]) -> str:
    uses: dict[str, set] = {}
    for f in findings:
        if f["family"] in VULNERABLE:
            uses.setdefault(f["family"], set()).update(["kex", "sig"] if f["use"] == "both" else [f["use"]])
    return " ".join(f"{fam}[{','.join(sorted(u))}]" for fam, u in sorted(uses.items()))


def build_inventory(root, scan_result: dict) -> dict:
    root = Path(root)
    dirs = service_dirs(root)
    by_service: dict[str, list[dict]] = {p: [] for p in dirs}
    unowned = []
    for f in scan_result["findings"]:
        if (p := owner(f["file"], dirs)) is None:
            unowned.append(f)
        else:
            by_service[p].append(f)
    assets, not_vulnerable = [], []
    for prefix, d in dirs.items():
        manifest = json.loads((d / MANIFEST).read_text())
        findings = by_service[prefix]
        vulnerable = [f for f in findings if f["family"] in VULNERABLE]
        evidence = [
            {k: f[k] for k in ("file", "line", "family", "use", "rule", "snippet")} for f in findings
        ]
        if not vulnerable:
            not_vulnerable.append({
                "id": manifest["id"],
                "needs_live_probe": any(f["family"] == "UNKNOWN" for f in findings),
                "evidence": evidence,
            })
            continue
        assets.append(
            {
                "id": manifest["id"],
                "name": manifest.get("name", manifest["id"]),
                "kind": manifest["kind"],
                "data_class": manifest["data_class"],
                "algorithm": algorithm_summary(vulnerable),
                "depends_on": manifest.get("depends_on", []),
                "pqc_present": any(f["family"] == "PQC" for f in findings),
                "evidence": evidence,
            }
        )
    known = {a["id"] for a in assets}
    for a in assets:  # a dependency that needs no migration cannot block one that does
        a["depends_on"] = [d for d in a["depends_on"] if d in known]
    return {
        "label": "Generated by detect/ from a static scan; ownership fields come from atlas-service.json manifests.",
        "assets": assets,
        "not_vulnerable": not_vulnerable,
        "unowned_findings": unowned,
    }
